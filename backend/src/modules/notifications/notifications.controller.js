// Institutional announcements, departmental notices, and email alerts: HTTP request handling and response dispatch
const service = require('./notifications.service');
const { success, error } = require('../../utils/responseHandler');

exports.getAll = async (req, res, next) => {
  try {
    const data = await service.findAll();
    return success(res, data, 'notifications retrieved successfully');
  } catch (err) {
    next(err);
  }
};

exports.getById = async (req, res, next) => {
  try {
    const data = await service.findById(req.params.id);
    return success(res, data, 'notifications record found');
  } catch (err) {
    next(err);
  }
};
