// Student attendance session tracking, aggregate statistics, and OCR results: HTTP request handling and response dispatch
const service = require('./attendance.service');
const { success, error } = require('../../utils/responseHandler');

exports.getAll = async (req, res, next) => {
  try {
    const data = await service.findAll();
    return success(res, data, 'attendance retrieved successfully');
  } catch (err) {
    next(err);
  }
};

exports.getById = async (req, res, next) => {
  try {
    const data = await service.findById(req.params.id);
    return success(res, data, 'attendance record found');
  } catch (err) {
    next(err);
  }
};
