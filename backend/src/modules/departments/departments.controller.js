// Academic department structure, faculty affiliations, and degree programs: HTTP request handling and response dispatch
const service = require('./departments.service');
const { success, error } = require('../../utils/responseHandler');

exports.getAll = async (req, res, next) => {
  try {
    const data = await service.findAll();
    return success(res, data, 'departments retrieved successfully');
  } catch (err) {
    next(err);
  }
};

exports.getById = async (req, res, next) => {
  try {
    const data = await service.findById(req.params.id);
    return success(res, data, 'departments record found');
  } catch (err) {
    next(err);
  }
};
